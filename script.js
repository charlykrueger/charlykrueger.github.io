function renderProject(slug, shouldUpdateHash = true) {
  const project = projects.find((item) => item.slug === slug);
  if (!project) return;

  activeProject = project;
  activeSingleIndex = 0;

  clearRunningIntervals();

  if (shouldUpdateHash) {
    history.replaceState(null, "", `#${project.slug}`);
  }

  document.title = `${project.title} — Charly Krüger`;
  sideTitle.textContent = `${project.number} ${project.title}`;

  projectView.innerHTML = "";

  const article = document.createElement("article");
  article.className = "project-page";

  const content = document.createElement("div");
  content.className = "project-content";

  if (project.layout === "single") {
    content.appendChild(createSingleGallery(project));
  }

  if (project.layout === "video" && project.youtube) {
    content.appendChild(createYouTubeBlock(project.youtube, project.title));
  }

  if (project.layout === "scroll") {
    content.appendChild(createRunningGalleryFromImages(project.galleryImages, project.title));
  }

  if (project.layout === "fashion") {
    content.appendChild(createRunningGalleryFromImages(project.galleryImages, project.title));
  }

  if (project.layout === "music") {
    content.appendChild(createRunningGalleryFromItems(project.galleryItems, project.title));
  }

  if (project.layout === "unlabeled") {
    content.appendChild(createRunningGalleryFromImages(project.galleryImages, project.title));
    content.appendChild(createUnlabeledPosters(project));
  }

  const text = document.createElement("div");
  text.className = "project-text";

  if (project.textHtml) {
    text.innerHTML = project.textHtml;
  } else {
    text.textContent = project.text || "";
  }

  content.appendChild(text);

  if (project.layout === "unlabeled") {
    content.appendChild(createUnlabeledCsdGallery(project));
  } else if (project.layout === "fashion") {
    content.appendChild(createFashionRows(project));
  } else if (project.layout === "music") {
    content.appendChild(createMusicRows(project));
  } else if (project.layout !== "video") {
    content.appendChild(createFixedImages(project));
  }

  article.appendChild(content);
  projectView.appendChild(article);

  window.scrollTo({ top: 0, behavior: "instant" });
}

function createSingleGallery(project) {
  const gallery = document.createElement("div");
  gallery.className = "single-gallery";

  project.galleryImages.forEach((src, index) => {
    const slide = document.createElement("div");
    slide.className = index === 0 ? "single-slide active" : "single-slide";

    const img = createImage(src, `${project.title}, image ${index + 1}`);
    setImageOrientationClass(img);

    img.addEventListener("click", () => openLightbox(project.galleryImages, index));

    slide.appendChild(img);
    gallery.appendChild(slide);
  });

  const prev = document.createElement("button");
  prev.className = "gallery-arrow gallery-prev";
  prev.type = "button";
  prev.textContent = "‹";
  prev.addEventListener("click", () => changeSingleSlide(-1));

  const next = document.createElement("button");
  next.className = "gallery-arrow gallery-next";
  next.type = "button";
  next.textContent = "›";
  next.addEventListener("click", () => changeSingleSlide(1));

  gallery.appendChild(prev);
  gallery.appendChild(next);

  return gallery;
}

function setImageOrientationClass(img) {
  function applyClass() {
    img.classList.remove("is-landscape", "is-portrait", "is-square");

    if (img.naturalWidth > img.naturalHeight) {
      img.classList.add("is-landscape");
    } else if (img.naturalHeight > img.naturalWidth) {
      img.classList.add("is-portrait");
    } else {
      img.classList.add("is-square");
    }
  }

  if (img.complete && img.naturalWidth) {
    applyClass();
  } else {
    img.addEventListener("load", applyClass, { once: true });
  }
}

function changeSingleSlide(direction) {
  const slides = Array.from(document.querySelectorAll(".single-slide"));
  if (!slides.length) return;

  slides[activeSingleIndex].classList.remove("active");

  activeSingleIndex =
    (activeSingleIndex + direction + slides.length) % slides.length;

  slides[activeSingleIndex].classList.add("active");
}

function flattenGalleryItems(items) {
  return items.flatMap((item) => Array.isArray(item) ? item : [item]);
}

